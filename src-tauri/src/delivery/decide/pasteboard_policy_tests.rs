#[test]
fn clipboard_generation_is_checked_after_slow_target_guard_before_text_dispatch() {
    let count = Cell::new(11);
    let result = before_dispatch(
        11,
        || {
            count.set(12);
            Ok(())
        },
        || count.get(),
    );
    assert!(result.is_err());
    assert!(before_dispatch(12, || Ok(()), || count.get()).is_ok());
    assert!(before_dispatch(12, || Err("retired target".into()), || count.get()).is_err());
}


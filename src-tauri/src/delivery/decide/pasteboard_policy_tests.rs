struct WriteBoard {
    generation: Cell<i64>,
    calls: RefCell<Vec<&'static str>>,
    copy_in_prepare: bool,
    copy_in_clear: bool,
    copy_in_write: bool,
    prepare_error: bool,
    write_error: bool,
}
impl WriteBoard {
    fn new() -> Self {
        Self {
            generation: Cell::new(10),
            calls: RefCell::default(),
            copy_in_prepare: false,
            copy_in_clear: false,
            copy_in_write: false,
            prepare_error: false,
            write_error: false,
        }
    }
}
impl Writer for WriteBoard {
    type Prepared = ();
    fn prepare(&self, _: &[Vec<(String, Vec<u8>)>]) -> Result<(), String> {
        self.calls.borrow_mut().push("prepare");
        if self.copy_in_prepare {
            self.generation.set(self.generation.get() + 1);
        }
        if self.prepare_error {
            Err("could not prepare".into())
        } else {
            Ok(())
        }
    }
    fn generation(&self) -> i64 {
        self.generation.get()
    }
    fn clear(&self, local: bool) -> i64 {
        assert!(local);
        self.calls.borrow_mut().push("clear");
        self.generation
            .set(self.generation.get() + if self.copy_in_clear { 2 } else { 1 });
        self.generation.get()
    }
    fn write(&self, _: &()) -> bool {
        self.calls.borrow_mut().push("write");
        if self.copy_in_write {
            self.generation.set(self.generation.get() + 1);
        }
        !self.write_error
    }
}

#[test]
fn publication_clear_or_write_generation_discontinuity_is_unknown() {
    for during_clear in [false, true] {
        let mut board = WriteBoard::new();
        board.copy_in_clear = during_clear;
        board.copy_in_write = !during_clear;
        let result = replace(&board, 10, &ReadBoard::rich().items, true);
        assert!(
            matches!(result, Err(PublicationFailure::Unknown(_))),
            "{result:?}"
        );
        if during_clear {
            assert_eq!(*board.calls.borrow(), ["prepare", "clear"]);
        }
    }
}

#[test]
fn publication_failure_stages_and_empty_restore_are_explicit() {
    let board = WriteBoard::new();
    assert_eq!(replace(&board, 10, &ReadBoard::rich().items, true), Ok(11));
    let mut board = WriteBoard::new();
    board.prepare_error = true;
    assert!(matches!(
        replace(&board, 10, &ReadBoard::rich().items, true),
        Err(PublicationFailure::Untouched(_))
    ));
    assert_eq!(*board.calls.borrow(), ["prepare"]);
    let mut board = WriteBoard::new();
    board.write_error = true;
    assert!(matches!(
        replace(&board, 10, &ReadBoard::rich().items, true),
        Err(PublicationFailure::Owned { generation: 11, .. })
    ));
    let board = WriteBoard::new();
    assert_eq!(replace(&board, 10, &[], true), Ok(11));
    assert_eq!(*board.calls.borrow(), ["prepare", "clear"]);
}

#[test]
fn publication_race_in_prepare_never_clears_newer_copy() {
    let mut board = WriteBoard::new();
    board.copy_in_prepare = true;
    let result = replace(&board, 10, &ReadBoard::rich().items, true);
    assert!(matches!(result, Err(PublicationFailure::Unknown(_))));
    assert_eq!(*board.calls.borrow(), ["prepare"]);
}

struct ReadBoard {
    items: Vec<Vec<(String, Vec<u8>)>>,
    generation: Cell<i64>,
    calls: RefCell<Vec<String>>,
    nil_items: bool,
    missing_data: bool,
    change_on_data: bool,
    change_on_types: bool,
}
impl ReadBoard {
    fn rich() -> Self {
        Self {
            items: vec![
                vec![
                    ("public.rtf".into(), vec![0, 255, 1]),
                    ("public.utf8-plain-text".into(), b"hello".to_vec()),
                ],
                vec![("public.png".into(), vec![9, 0, 8])],
            ],
            generation: Cell::new(10),
            calls: RefCell::default(),
            nil_items: false,
            missing_data: false,
            change_on_data: false,
            change_on_types: false,
        }
    }
}
impl Reader for ReadBoard {
    type Item = usize;
    fn generation(&self) -> i64 {
        self.generation.get()
    }
    fn items(&self, _: usize) -> Result<Vec<usize>, String> {
        self.calls.borrow_mut().push("items".into());
        if self.nil_items {
            return Err("nil items".into());
        }
        Ok((0..self.items.len()).collect())
    }
    fn types(&self, i: &usize, _: usize) -> Result<Vec<String>, String> {
        self.calls.borrow_mut().push(format!("types {i}"));
        if self.change_on_types {
            self.generation.set(self.generation.get() + 1);
        }
        Ok(self.items[*i].iter().map(|(ty, _)| ty.clone()).collect())
    }
    fn data(&self, i: &usize, ty: &str, remaining: usize) -> Result<Vec<u8>, String> {
        self.calls.borrow_mut().push(format!("data {i} {ty}"));
        if self.missing_data {
            return Err("provider unavailable".into());
        }
        if self.change_on_data {
            self.generation.set(self.generation.get() + 1);
        }
        let bytes = &self.items[*i].iter().find(|(t, _)| t == ty).unwrap().1;
        if bytes.len() > remaining {
            return Err("over budget".into());
        }
        Ok(bytes.clone())
    }
}

#[test]
fn captures_all_ordered_formats_bytes_and_metadata_before_payload() {
    let board = ReadBoard::rich();
    let snapshot = capture(&board).unwrap();
    assert_eq!(snapshot.generation, 10);
    assert_eq!(snapshot.items, board.items);
    let calls = board.calls.borrow();
    assert_eq!(&calls[..3], ["items", "types 0", "types 1"]);
}

#[test]
fn concealed_on_later_item_refuses_before_reading_any_payload() {
    let mut board = ReadBoard::rich();
    board.items[1].push((CONCEALED.into(), Vec::new()));
    assert!(capture(&board).is_err());
    assert!(!board.calls.borrow().iter().any(|c| c.starts_with("data")));
}

#[test]
fn generation_change_during_metadata_or_provider_refuses_snapshot() {
    for metadata in [false, true] {
        let mut board = ReadBoard::rich();
        board.change_on_types = metadata;
        board.change_on_data = !metadata;
        assert!(capture(&board).is_err());
        let reads = board
            .calls
            .borrow()
            .iter()
            .filter(|c| c.starts_with("data"))
            .count();
        assert_eq!(reads, if metadata { 0 } else { 1 });
    }
}

#[test]
fn item_without_representations_is_not_a_complete_snapshot() {
    let mut board = ReadBoard::rich();
    board.items[1].clear();
    assert!(capture(&board).is_err());
    assert!(!board.calls.borrow().iter().any(|c| c.starts_with("data")));
}

#[test]
fn empty_is_valid_but_nil_items_or_missing_representation_is_not() {
    let mut board = ReadBoard::rich();
    board.items.clear();
    assert!(capture(&board).unwrap().items.is_empty());
    board.nil_items = true;
    assert!(capture(&board).is_err());
    let mut board = ReadBoard::rich();
    board.missing_data = true;
    assert!(capture(&board).is_err());
    let mut board = ReadBoard::rich();
    board.items[0][0].1.clear();
    assert_eq!(capture(&board).unwrap().items, board.items);
}

#[test]
fn bounded_snapshot_rejects_metadata_and_total_bytes() {
    for case in 0..5 {
        let mut board = ReadBoard::rich();
        match case {
            0 => board.items = vec![vec![("type".into(), vec![])]; MAX_ITEMS + 1],
            1 => {
                board.items[0] = (0..=MAX_TYPES_PER_ITEM)
                    .map(|i| (format!("type{i}"), vec![]))
                    .collect()
            }
            2 => board.items[0][0].0 = "x".repeat(MAX_TYPE_NAME_BYTES + 1),
            3 => {
                board.items = vec![
                    (0..MAX_TYPES_PER_ITEM)
                        .map(|i| (format!("type{i}"), vec![]))
                        .collect();
                    MAX_TYPES / MAX_TYPES_PER_ITEM + 1
                ]
            }
            _ => {
                board.items = vec![vec![
                    ("a".into(), vec![0; MAX_BYTES]),
                    ("b".into(), vec![1]),
                ]]
            }
        }
        assert!(capture(&board).is_err(), "case {case}");
        if case < 4 {
            assert!(!board.calls.borrow().iter().any(|c| c.starts_with("data")));
        }
    }
}

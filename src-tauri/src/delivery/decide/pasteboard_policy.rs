//! Bounded, metadata-first clipboard policy. No AppKit calls in this module.

pub const MAX_ITEMS: usize = 64;
pub const MAX_TYPES_PER_ITEM: usize = 128;
pub const MAX_TYPES: usize = 1024;
pub const MAX_TYPE_NAME_BYTES: usize = 1024;
pub const MAX_BYTES: usize = 32 * 1024 * 1024;
pub const CONCEALED: &str = "org.nspasteboard.ConcealedType";
pub const STRING: &str = "public.utf8-plain-text";
pub const TRANSIENT: &str = "org.nspasteboard.TransientType";
pub const AUTOGENERATED: &str = "org.nspasteboard.AutoGeneratedType";

pub fn before_dispatch(
    expected: i64,
    target: impl Fn() -> Result<(), String>,
    generation: impl Fn() -> i64,
) -> Result<(), String> {
    target()?;
    if generation() != expected {
        Err("clipboard changed before text-key dispatch".into())
    } else {
        Ok(())
    }
}

pub fn transient_items(text: &str) -> Vec<Vec<(String, Vec<u8>)>> {
    vec![vec![
        (STRING.into(), text.as_bytes().to_vec()),
        (TRANSIENT.into(), Vec::new()),
        (CONCEALED.into(), Vec::new()),
        (AUTOGENERATED.into(), Vec::new()),
    ]]
}

pub fn validate_data_extent(len: usize, has_bytes: bool, remaining: usize) -> Result<(), String> {
    if len > remaining {
        Err("clipboard exceeds byte limit".into())
    } else if len != 0 && !has_bytes {
        Err("clipboard data buffer unavailable".into())
    } else {
        Ok(())
    }
}

#[derive(Debug, PartialEq, Eq)]
pub enum PublicationFailure {
    Untouched(String),
    Owned { generation: i64, reason: String },
    Unknown(String),
}

pub trait Writer {
    type Prepared;
    /// Allocate and populate ALL items before any pasteboard mutation.
    fn prepare(&self, items: &[Vec<(String, Vec<u8>)>]) -> Result<Self::Prepared, String>;
    fn generation(&self) -> i64;
    /// Returns the new ownership generation, not a later sampled count.
    fn clear(&self, local_only: bool) -> i64;
    fn write(&self, prepared: &Self::Prepared) -> bool;
}

pub fn replace(
    writer: &impl Writer,
    expected: i64,
    items: &[Vec<(String, Vec<u8>)>],
    local_only: bool,
) -> Result<i64, PublicationFailure> {
    let prepared = writer
        .prepare(items)
        .map_err(PublicationFailure::Untouched)?;
    if writer.generation() != expected {
        return Err(PublicationFailure::Unknown(
            "clipboard changed before clear".into(),
        ));
    }
    let cleared = writer.clear(local_only);
    // AppKit clear/prepare changes ownership exactly once. writeObjects adds
    // representations to that ownership, not a second ownership declaration.
    // A discontinuity can already have lost an external copy in the non-CAS
    // check/clear gap: detect it, never claim preservation or restore stale data.
    if expected.checked_add(1) != Some(cleared) || writer.generation() != cleared {
        return Err(PublicationFailure::Unknown(
            "clipboard ownership changed during clear".into(),
        ));
    }
    let wrote = items.is_empty() || writer.write(&prepared);
    if writer.generation() != cleared {
        return Err(PublicationFailure::Unknown(
            "clipboard ownership changed during publication".into(),
        ));
    }
    if !wrote {
        return Err(PublicationFailure::Owned {
            generation: cleared,
            reason: "pasteboard refused prepared items".into(),
        });
    }
    Ok(cleared)
}

#[derive(Debug, PartialEq, Eq)]
pub struct Snapshot {
    pub generation: i64,
    pub items: Vec<Vec<(String, Vec<u8>)>>,
}

pub trait Reader {
    /// Pin original item references. Enforce limit before allocating/copying.
    type Item;
    fn generation(&self) -> i64;
    /// Nil is a read error, not an empty clipboard.
    fn items(&self, limit: usize) -> Result<Vec<Self::Item>, String>;
    fn types(&self, item: &Self::Item, limit: usize) -> Result<Vec<String>, String>;
    /// Check NSData length before copying; never turn a nil buffer into empty.
    fn data(&self, item: &Self::Item, ty: &str, remaining: usize) -> Result<Vec<u8>, String>;
}

pub fn capture(reader: &impl Reader) -> Result<Snapshot, String> {
    let generation = reader.generation();
    let items = reader.items(MAX_ITEMS)?;
    if items.len() > MAX_ITEMS {
        return Err("too many clipboard items".into());
    }
    let mut metadata = Vec::with_capacity(items.len());
    let mut total_types = 0;
    for item in &items {
        unchanged(reader, generation)?;
        let types = reader.types(item, MAX_TYPES_PER_ITEM)?;
        if types.is_empty() {
            return Err("clipboard item has no readable representations".into());
        }
        total_types += types.len();
        if types.len() > MAX_TYPES_PER_ITEM
            || total_types > MAX_TYPES
            || types
                .iter()
                .any(|t| t.is_empty() || t.len() > MAX_TYPE_NAME_BYTES || t.contains('\0'))
        {
            return Err("clipboard metadata exceeds snapshot limit".into());
        }
        if types.iter().any(|ty| ty == CONCEALED) {
            return Err("concealed clipboard cannot be preserved".into());
        }
        metadata.push(types);
    }
    let mut saved = Vec::with_capacity(items.len());
    let mut remaining = MAX_BYTES;
    for (item, types) in items.iter().zip(metadata) {
        let mut entries = Vec::with_capacity(types.len());
        for ty in types {
            unchanged(reader, generation)?;
            let bytes = reader.data(item, &ty, remaining)?;
            unchanged(reader, generation)?;
            remaining = remaining
                .checked_sub(bytes.len())
                .ok_or("clipboard exceeds byte limit")?;
            entries.push((ty, bytes));
        }
        saved.push(entries);
    }
    unchanged(reader, generation)?;
    Ok(Snapshot {
        generation,
        items: saved,
    })
}

fn unchanged(reader: &impl Reader, expected: i64) -> Result<(), String> {
    if reader.generation() != expected {
        Err("clipboard changed during snapshot".into())
    } else {
        Ok(())
    }
}

